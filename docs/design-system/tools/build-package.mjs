// Builds the @loomwatch/design-system package that /design-sync converts for Claude Design:
//   dist/types/  .d.ts for src/index.ts and everything it reaches in ui/src (ui's own tsc)
//   dist/loomwatch.css  tokens.css + components.css, the stylesheet every design receives
// Run tools/sync.sh first so tokens.css matches the app.
//   node docs/design-system/tools/build-package.mjs
import { spawnSync } from 'node:child_process'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repo = resolve(pkg, '../..')
const dist = join(pkg, 'dist')
rmSync(dist, { recursive: true, force: true })

// Declarations come from the app's TypeScript, so the props Claude Design sees are the real ones.
// rootDir is the repo, because the entry re-exports from ui/src; index.d.ts re-exports the entry
// from the top of that tree so the whole tree sits under one types root.
const types = join(dist, 'types')
const tsc = spawnSync(join(repo, 'ui/node_modules/.bin/tsc'), [
  join(pkg, 'src/index.ts'),
  '--declaration', '--emitDeclarationOnly', '--outDir', types, '--rootDir', repo,
  '--jsx', 'react-jsx', '--module', 'esnext', '--moduleResolution', 'bundler', '--target', 'es2022',
  '--lib', 'es2022,dom', '--skipLibCheck', '--strict',
], { stdio: 'inherit' })
if (tsc.status !== 0) process.exit(tsc.status ?? 1)
writeFileSync(join(types, 'index.d.ts'), "export * from './docs/design-system/src/index'\n")

mkdirSync(dist, { recursive: true })
const header = '/* LoomWatch design system: tokens.css + components.css. Generated by tools/build-package.mjs. */\n'
writeFileSync(join(dist, 'loomwatch.css'),
  header + readFileSync(join(pkg, 'tokens.css'), 'utf8') + '\n' + readFileSync(join(pkg, 'components.css'), 'utf8'))
console.log(`built ${dist}`)
